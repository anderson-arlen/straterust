pub fn apply(
    pud: &Pud,
    number: usize,
    expansion: bool,
    rules: &mut Rules,
    map: &mut Map,
    mission: &mut Mission,
) {
    let race = usize::from(pud.sides[pud.local]);
    let index = if expansion { 28 + race * 12 } else { race * 14 } + number - 1;
    let limits = &CAMPAIGNS[index];
    let excluded: &[u16] = match (expansion, race, number) {
        (true, 0, 2) => &[70, 72],
        (true, 0, 5) => &[42, 70],
        (true, 0, 7) => &[60, 64, 78, 82, 88],
        (true, 1, 2..=5) => &[43, 71],
        _ => &[],
    };
    for player in 0..16 {
        map.creation.insert(
            PlayerId(player),
            limits
                .units
                .iter()
                .filter(|n| !excluded.contains(n))
                .map(|n| id(usize::from(*n)))
                .filter(|id| rules.units.iter().any(|u| u.id == *id))
                .collect(),
        );
    }
    // There are no per-player research permissions yet, so all campaign slots use
    // the authored technology list, as the original campaign permissions do.
    for research in &mut rules.research {
        research.available = limits.research.contains(&research.id.0);
    }
    let grants: Vec<_> = (0..16)
        .flat_map(|player| {
            limits
                .granted
                .iter()
                .map(move |r| MissionAction::GrantResearch {
                    player: PlayerId(player),
                    research: ResearchId(*r),
                })
        })
        .collect();
    for actions in grants.chunks(64) {
        mission.triggers.push(MissionTrigger {
            conditions: vec![MissionCondition::Elapsed {
                comparison: MissionComparison::AtLeast,
                milliseconds: 0,
            }],
            actions: actions.to_vec(),
        });
    }
}
