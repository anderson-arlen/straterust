use anyhow::{Result, bail, ensure};

const MAX_SECTOR: usize = 65_536;
const HEAD: usize = 0;
const NODE_COUNT: usize = 516; // 515 tree nodes and one linked-list sentinel.

/// Decode only the audio combinations actually used by classic MPQ archives.
/// `expected` is the final sector size, and also bounds the Huffman intermediate.
pub(super) fn decode(mask: u8, input: &[u8], expected: usize) -> Result<Vec<u8>> {
    ensure!(
        (1..=MAX_SECTOR).contains(&expected),
        "invalid audio sector size"
    );
    ensure!(
        input.len() <= MAX_SECTOR,
        "audio sector input exceeds limit"
    );
    ensure!(
        matches!(mask, 0x01 | 0x40 | 0x41 | 0x80 | 0x81),
        "unsupported MPQ audio compression mask {mask:#04x}"
    );
    let intermediate;
    let bytes = if mask & 1 != 0 {
        intermediate = huffman(input, expected)?;
        &intermediate[..]
    } else {
        input
    };
    let output = if mask & 0xc0 != 0 {
        adpcm(bytes, if mask & 0x80 != 0 { 2 } else { 1 }, expected)?
    } else {
        bytes.to_vec()
    };
    ensure!(
        output.len() == expected,
        "decoded audio sector size mismatch"
    );
    Ok(output)
}

struct Bits<'a> {
    input: &'a [u8],
    offset: usize,
}

impl Bits<'_> {
    fn take(&mut self, count: usize) -> Result<u16> {
        ensure!(
            self.offset + count <= self.input.len() * 8,
            "truncated Huffman stream"
        );
        let mut value = 0;
        for shift in 0..count {
            value |= u16::from((self.input[self.offset / 8] >> (self.offset % 8)) & 1) << shift;
            self.offset += 1;
        }
        Ok(value)
    }
}

#[derive(Clone, Copy, Default)]
struct Node {
    next: usize,
    prev: usize,
    parent: Option<usize>,
    low: Option<usize>,
    value: u16,
    weight: u32,
}

struct Tree {
    nodes: [Node; NODE_COUNT],
    symbols: [Option<usize>; 258],
    used: usize,
}

impl Tree {
    fn new(distribution: &[u8; 256]) -> Result<Self> {
        let mut tree = Self {
            nodes: [Node::default(); NODE_COUNT],
            symbols: [None; 258],
            used: 1,
        };
        let mut max_weight = 0;
        for (value, &weight) in distribution.iter().enumerate() {
            if weight != 0 {
                let node = tree.create(value as u16, u32::from(weight), HEAD)?;
                tree.symbols[value] = Some(node);
                max_weight = tree.fix_position(node, max_weight);
            }
        }
        for value in [256, 257] {
            let node = tree.create(value as u16, 1, tree.nodes[HEAD].prev)?;
            tree.symbols[value] = Some(node);
        }
        let mut low = tree.nodes[HEAD].prev;
        while low != HEAD {
            let high = tree.nodes[low].prev;
            if high == HEAD {
                break;
            }
            let parent = tree.create(0, tree.nodes[low].weight + tree.nodes[high].weight, HEAD)?;
            tree.nodes[low].parent = Some(parent);
            tree.nodes[high].parent = Some(parent);
            tree.nodes[parent].low = Some(low);
            max_weight = tree.fix_position(parent, max_weight);
            low = tree.nodes[high].prev;
        }
        Ok(tree)
    }

    fn link_after(&mut self, after: usize, node: usize) {
        let next = self.nodes[after].next;
        self.nodes[node].next = next;
        self.nodes[node].prev = after;
        self.nodes[next].prev = node;
        self.nodes[after].next = node;
    }

    fn remove(&mut self, node: usize) {
        let Node { prev, next, .. } = self.nodes[node];
        self.nodes[prev].next = next;
        self.nodes[next].prev = prev;
    }

    fn create(&mut self, value: u16, weight: u32, after: usize) -> Result<usize> {
        ensure!(self.used < NODE_COUNT, "Huffman tree exceeds node limit");
        let node = self.used;
        self.used += 1;
        self.nodes[node].value = value;
        self.nodes[node].weight = weight;
        self.link_after(after, node);
        Ok(node)
    }

    fn higher_or_equal(&self, mut node: usize, weight: u32) -> usize {
        while node != HEAD && self.nodes[node].weight < weight {
            node = self.nodes[node].prev;
        }
        node
    }

    fn fix_position(&mut self, node: usize, maximum: u32) -> u32 {
        let weight = self.nodes[node].weight;
        if weight < maximum {
            let higher = self.higher_or_equal(self.nodes[HEAD].prev, weight);
            self.remove(node);
            self.link_after(higher, node);
        }
        maximum.max(weight)
    }

    fn increment(&mut self, mut current: Option<usize>) -> Result<()> {
        // The limit also makes corrupted/cyclic trees fail instead of looping.
        for _ in 0..NODE_COUNT {
            let Some(node) = current else { return Ok(()) };
            self.nodes[node].weight += 1; // At most one sector's symbols.
            let higher = self.higher_or_equal(self.nodes[node].prev, self.nodes[node].weight);
            let high = self.nodes[higher].next;
            if high != node {
                self.remove(high);
                self.link_after(node, high);
                self.remove(node);
                self.link_after(higher, node);
                let parent = self.nodes[node]
                    .parent
                    .ok_or_else(|| anyhow::anyhow!("invalid Huffman parent"))?;
                let high_parent = self.nodes[high]
                    .parent
                    .ok_or_else(|| anyhow::anyhow!("invalid Huffman sibling"))?;
                let low = self.nodes[high_parent].low;
                if self.nodes[parent].low == Some(node) {
                    self.nodes[parent].low = Some(high);
                }
                if low == Some(high) {
                    self.nodes[high_parent].low = Some(node);
                }
                self.nodes[node].parent = Some(high_parent);
                self.nodes[high].parent = Some(parent);
            }
            current = self.nodes[node].parent;
        }
        bail!("cyclic Huffman tree")
    }

    fn insert_symbol(&mut self, value: u16) -> Result<()> {
        ensure!(
            self.symbols[usize::from(value)].is_none(),
            "duplicate Huffman escape symbol"
        );
        let last = self.nodes[HEAD].prev;
        let old_value = self.nodes[last].value;
        let high = self.create(old_value, self.nodes[last].weight, self.nodes[HEAD].prev)?;
        self.nodes[high].parent = Some(last);
        self.symbols[usize::from(old_value)] = Some(high);
        let low = self.create(value, 0, self.nodes[HEAD].prev)?;
        self.nodes[low].parent = Some(last);
        self.nodes[last].low = Some(low);
        self.symbols[usize::from(value)] = Some(low);
        self.increment(Some(low))
    }

    fn symbol(&self, bits: &mut Bits<'_>) -> Result<u16> {
        let mut node = self.nodes[HEAD].next;
        for _ in 0..NODE_COUNT {
            let Some(low) = self.nodes[node].low else {
                return Ok(self.nodes[node].value);
            };
            node = if bits.take(1)? != 0 {
                self.nodes[low].prev
            } else {
                low
            };
            ensure!(node != HEAD, "invalid Huffman child");
        }
        bail!("cyclic Huffman tree")
    }
}

fn huffman(input: &[u8], limit: usize) -> Result<Vec<u8>> {
    let mut bits = Bits { input, offset: 0 };
    let kind = usize::from(bits.take(8)?);
    let distribution = DISTRIBUTIONS
        .get(kind)
        .ok_or_else(|| anyhow::anyhow!("unsupported Huffman distribution {kind}"))?;
    let mut tree = Tree::new(distribution)?;
    let mut output = Vec::with_capacity(limit);
    loop {
        let mut value = tree.symbol(&mut bits)?;
        if value == 256 {
            // The end symbol is mandatory even when the output limit is reached.
            ensure!(input.len() * 8 - bits.offset < 8, "trailing Huffman data");
            return Ok(output);
        }
        ensure!(output.len() < limit, "Huffman output exceeds sector size");
        if value == 257 {
            value = bits.take(8)?;
            tree.insert_symbol(value)?;
            if kind != 0 {
                tree.increment(tree.symbols[usize::from(value)])?;
            }
        }
        output.push(value as u8);
        if kind == 0 {
            tree.increment(tree.symbols[usize::from(value)])?;
        }
    }
}

fn adpcm(input: &[u8], channels: usize, expected: usize) -> Result<Vec<u8>> {
    let header = 2 + channels * 2;
    ensure!(input.len() >= header, "truncated ADPCM header");
    ensure!(input[0] == 0 && input[1] <= 31, "invalid ADPCM header");
    ensure!(
        expected >= channels * 2 && expected.is_multiple_of(channels * 2),
        "invalid ADPCM output size"
    );
    let mut samples = [0_i32; 2];
    let mut steps = [44_usize; 2];
    let mut output = Vec::with_capacity(expected);
    for (channel, sample) in samples.iter_mut().enumerate().take(channels) {
        *sample = i32::from(i16::from_le_bytes([
            input[2 + channel * 2],
            input[3 + channel * 2],
        ]));
        output.extend_from_slice(&(*sample as i16).to_le_bytes());
    }
    let mut channel = channels - 1;
    for &encoded in &input[header..] {
        channel = (channel + 1) % channels;
        if encoded == 0x81 {
            steps[channel] = (steps[channel] + 8).min(88);
            channel = (channel + 1) % channels;
            continue;
        }
        ensure!(
            output.len() + 2 <= expected,
            "ADPCM output exceeds sector size"
        );
        if encoded == 0x80 {
            steps[channel] = steps[channel].saturating_sub(1);
        } else {
            let step = STEP_SIZES[steps[channel]];
            let mut difference = step >> input[1];
            for bit in 0..6 {
                if encoded & (1 << bit) != 0 {
                    difference += step >> bit;
                }
            }
            let predicted = if encoded & 0x40 != 0 {
                samples[channel] - difference
            } else {
                samples[channel] + difference
            };
            samples[channel] = predicted.clamp(i32::from(i16::MIN), i32::from(i16::MAX));
            steps[channel] = (steps[channel] as i32 + NEXT_STEP[usize::from(encoded & 0x1f)])
                .clamp(0, 88) as usize;
        }
        output.extend_from_slice(&(samples[channel] as i16).to_le_bytes());
    }
    ensure!(output.len() == expected, "truncated ADPCM samples");
    Ok(output)
}

